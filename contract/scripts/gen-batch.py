#!/usr/bin/env python3
"""Generate contract/src/batch.compact: the settlement batch size.

Compact vectors have a fixed length, so the number of tickets one settlement
proof covers is fixed when the contract is compiled. This script writes the
few declarations that depend on it.

    python3 contract/scripts/gen-batch.py 25

The proving-key size grows with the batch: see docs/SETTLEMENT.md for the
measured circuit sizes.
"""
import pathlib
import sys

size = int(sys.argv[1]) if len(sys.argv) > 1 else 25
if not 1 <= size <= 200:
    sys.exit("batch size must be 1..200")

slots = ", ".join(str(i) for i in range(size))
out = f"""// GENERATED by contract/scripts/gen-batch.py; edit that script, not this file.
//
// Settlement batch size: one settleBatch proof covers {size} tickets (fewer in
// a draw's last batch). Included by settlement.compact after TicketPreimage.

// The tickets at indexes first, first + 1, ... of a draw, decrypted by whoever
// settles (the settlement key holder). Slots past the draw's last ticket are
// ignored; any value will do.
witness settlementBatch(drawId: Uint<32>, first: Uint<64>): Vector<{size}, TicketPreimage>;

export pure circuit batchSize(): Uint<64> {{
  return {size};
}}

pure circuit batchSlots(): Vector<{size}, Uint<64>> {{
  return [{slots}];
}}
"""
target = pathlib.Path(__file__).resolve().parent.parent / "src" / "batch.compact"
target.write_text(out)
print(f"wrote {target} (batch size {size})")
