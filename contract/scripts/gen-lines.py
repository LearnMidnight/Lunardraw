#!/usr/bin/env python3
"""Generate contract/src/lines.compact: the extra standard lines a ticket carries.

A ticket is one entry plus up to LINES extra standard games ("lines"), so a
QuickPick package fills tickets of LINES + 1 games. Compact vectors have a
fixed length, so LINES is fixed when the contract is compiled, and scoring a
ticket's lines is written out line by line: summed this way, a count's size is
known to the compiler and needs no range check (a fold would check one per
line, about three times the cost).

    python3 contract/scripts/gen-lines.py 11

settlement.compact declares the vectors whose length follows from LINES
(TicketPreimage.lines, SealedTicket.body, TicketHashInput.lines); this script
checks they match. See docs/SETTLEMENT.md for the measured circuit sizes.
"""
import pathlib
import re
import sys

lines = int(sys.argv[1]) if len(sys.argv) > 1 else 11
if not 0 <= lines <= 30:
    sys.exit("lines per ticket must be 0..30")

# Lines are packed three to a field element (8 bytes each: 7 numbers and the
# Moonball, 24 bytes), after the ticket's own 8 fields (see packTicket).
fields = max((lines + 2) // 3, 1)
body = 8 + fields

src_dir = pathlib.Path(__file__).resolve().parent.parent / "src"
settlement = (src_dir / "settlement.compact").read_text()
want = {
    r"lines: Vector<(\d+), Line>;": lines,
    r"body: Vector<(\d+), Field>;": body,
    r"lines: Vector<(\d+), Field>;": fields,
}
for pattern, n in want.items():
    m = re.search(pattern, settlement)
    if not m or int(m.group(1)) != n:
        sys.exit(f"settlement.compact: expected {pattern.replace('(\\d+)', str(n))} for {lines} lines")

line = lambda i: f"t.lines[{i}]" if i < lines else "noLine()"
packed = ",\n    ".join(f"packLines({line(3 * g)}, {line(3 * g + 1)}, {line(3 * g + 2)})" for g in range(fields))
games = "".join(f"\n       + (lineUsed(t.lines[{i}]) ? 1 : 0)" for i in range(lines))
q = "\n  ".join(f"const q{g} = (f[{8 + g}] as Bytes<24>) as Vector<24, Uint<8>>;" for g in range(fields))
unl = lambda i: (f"Line {{ numbers: [{', '.join(f'q{i // 3}[{8 * (i % 3) + k}]' for k in range(7))}], "
                 f"moonball: q{i // 3}[{8 * (i % 3) + 7}] }}")
unpacked = ",\n    ".join(unl(i) for i in range(lines))
per_line = "\n  ".join(f"const h{i} = lineHits(t.lines[{i}], numbers);\n  const m{i} = t.lines[{i}].moonball == moonball;"
                       for i in range(lines))
# Division j's condition on a line with h of its numbers drawn and m = its
# Moonball drawn, division 1 first (the same order as gamesByDivision).
conditions = ["h{i} == 7 && m{i}", "h{i} == 7 && !m{i}", "h{i} == 6 && m{i}", "h{i} == 6 && !m{i}", "h{i} == 5 && m{i}",
              "h{i} == 4 && m{i}", "h{i} == 5 && !m{i}", "h{i} == 3 && m{i}", "h{i} == 2 && m{i}"]
divisions = ",\n    ".join(
    f"(g[{j}]" + "".join(f"\n       + ({c.format(i=i)} ? 1 : 0)" for i in range(lines)) + ") as Uint<32>"
    for j, c in enumerate(conditions))
weights = ", ".join(str(256 ** i) for i in range(24))
slots = ", ".join(str(i) for i in range(body))

out = f"""// GENERATED by contract/scripts/gen-lines.py; edit that script, not this file.
//
// A ticket carries its entry and up to {lines} extra standard lines, so it holds
// up to {lines + 1} games. Lines are packed three to a field element, so a sealed
// ticket is {body} field elements. Included by settlement.compact after entries.

export pure circuit maxLines(): Uint<8> {{
  return {lines};
}}

// Games in a ticket: its entry's, plus one per line it uses.
export pure circuit ticketGames(t: TicketPreimage): Uint<32> {{
  return (gamesIn(t.entry){games}) as Uint<32>;
}}

// A ticket's winning games per division (division 1 first): its entry's and
// its lines'. An unused line wins nothing: 0 is never drawn, nor Moonball 0.
export pure circuit ticketDivisions(t: TicketPreimage, numbers: Vector<7, Uint<8>>, moonball: Uint<8>): Vector<9, Uint<32>> {{
  {per_line}
  const g = gamesByDivision(t.entry, numbers, moonball);
  return [
    {divisions}
  ];
}}

// 256^0 .. 256^23: three lines' 24 bytes as a Field, least significant byte first.
pure circuit weights24(): Vector<24, Field> {{
  return [{weights}];
}}

// A ticket's lines as field elements, three lines (24 bytes) each.
pure circuit packedLines(t: TicketPreimage): Vector<{fields}, Field> {{
  return [
    {packed}
  ];
}}

// The lines back from the sealed ticket's last {fields} field elements (off-chain, by the settler).
pure circuit unpackLines(f: Vector<{body}, Field>): Vector<{lines}, Line> {{
  {q}
  return [
    {unpacked}
  ];
}}

pure circuit bodySlots(): Vector<{body}, Field> {{
  return [{slots}];
}}
"""
target = src_dir / "lines.compact"
target.write_text(out)
print(f"wrote {target} ({lines} lines per ticket, {body} sealed fields)")
