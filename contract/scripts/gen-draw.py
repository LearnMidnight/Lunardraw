#!/usr/bin/env python3
"""Generate lotto/src/draw.compact: the Lunardraw draw rule as circuits.

Compact vectors are fixed-size and can't be built in loops, so the long
element lists (64 hex characters, 16 byte pairs per digest) are written out
here. Run from the repo root after changing it:

    python3 lotto/scripts/gen-draw.py

The rule (identical to the site's verification page, theme notes "Draw
verification scheme"):

    drawSeed  = SHA-256(seedHex + ":" + outputHex)
    main      for i = 0, 1, ...: d = SHA-256(drawSeedHex + ":" + i), 2-byte
              big-endian chunks, skip v >= 65536 - (65536 mod 35),
              n = v mod 35 + 1, skip repeats, stop at 7, sort
    Moonball  the same on drawSeedHex + ":mb", 1 from 20
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "draw.compact"

MAIN_DIGESTS = 3  # 48 candidates; fewer than 7 distinct is < 1e-30
HEX64 = ", ".join(f"...pairs[{i}]" for i in range(32))
PAIRS16 = ", ".join(f"[b[{2 * k}], b[{2 * k + 1}]]" for k in range(16))
IDX7 = "[0, 1, 2, 3, 4, 5, 6]"


def main_digests() -> str:
    return "\n".join(
        f"    const d{i} = pairsOf(sha66([...seedHex, 58, {48 + i}]));" for i in range(MAIN_DIGESTS)
    )


def main_folds() -> str:
    lines = ["    const s0 = Pick { nums: [0, 0, 0, 0, 0, 0, 0], count: 0 };"]
    for i in range(MAIN_DIGESTS):
        lines.append(f"    const s{i + 1} = fold(pickMain, s{i}, d{i});")
    return "\n".join(lines)


SRC = f"""// GENERATED by lotto/scripts/gen-draw.py; edit that script, not this file.
//
// The Lunardraw draw rule (Starfall: 7 from 35 + Moonball) as circuits, matching
// the site's verification page byte for byte:
//
//     drawSeed = SHA-256(seedHex + ":" + outputHex)
//     main     for i = 0, 1, 2: d = SHA-256(drawSeedHex + ":" + i); read 2 bytes
//              at a time; skip v >= 65520; n = v mod 35 + 1; skip repeats;
//              stop at 7; sort
//     Moonball the same on drawSeedHex + ":mb", 1 from 20
//
// Compact has no division, so each `v mod m` takes the quotient from the
// `divMod16` witness and checks v = m*q + r with r < m. Hex digits come from
// the `splitByte` witness, checked the same way. Sorting takes the order from
// `sortSeven` and checks the result is increasing and made of the same values.
// A dishonest witness can only make the proof fail, never change a number.

module StarfallDraw {{
  import CompactStandardLibrary;

  witness splitByte(x: Uint<8>): [Uint<8>, Uint<8>];
  witness divMod16(v: Uint<16>, m: Uint<16>): [Uint<16>, Uint<16>];
  witness sortSeven(v: Vector<7, Uint<8>>): Vector<7, Uint<8>>;

  export struct Numbers {{
    main: Vector<7, Uint<8>>;
    moonball: Uint<8>;
  }}

  struct Pick {{
    nums: Vector<7, Uint<8>>;
    count: Uint<8>;
  }}

  struct PickOne {{
    n: Uint<8>;
    found: Boolean;
  }}

  pure circuit hexChar(n: Uint<8>): Uint<8> {{
    return (n < 10 ? n + 48 : n + 87) as Uint<8>;
  }}

  circuit hexPair(x: Uint<8>): Vector<2, Uint<8>> {{
    const p = disclose(splitByte(x));
    assert(p[0] < 16 && p[1] < 16, "bad hex digit");
    assert((p[0] * 16 + p[1]) as Uint<8> == x, "bad byte split");
    return [hexChar(p[0]), hexChar(p[1])];
  }}

  // 32 bytes as 64 lowercase hex ASCII characters.
  export circuit toHex(b: Bytes<32>): Vector<64, Uint<8>> {{
    const pairs = map(hexPair, b);
    return [{HEX64}];
  }}

  pure circuit sha66(v: Vector<66, Uint<8>>): Bytes<32> {{
    return persistentHash<Bytes<66>>(v as Bytes<66>);
  }}

  pure circuit sha69(v: Vector<69, Uint<8>>): Bytes<32> {{
    return persistentHash<Bytes<69>>(v as Bytes<69>);
  }}

  // SHA-256 of 64 hex characters (a seed commitment, as the site publishes).
  export circuit seedCommitmentOf(seed: Bytes<32>): Bytes<32> {{
    return persistentHash<Bytes<64>>(toHex(seed) as Bytes<64>);
  }}

  // drawSeed = SHA-256(seedHex + ":" + outputHex)
  export circuit drawSeedOf(seed: Bytes<32>, output: Bytes<32>): Bytes<32> {{
    const v: Vector<129, Uint<8>> = [...toHex(seed), 58, ...toHex(output)];
    return persistentHash<Bytes<129>>(v as Bytes<129>);
  }}

  pure circuit pairsOf(b: Bytes<32>): Vector<16, Vector<2, Uint<8>>> {{
    return [{PAIRS16}];
  }}

  pure circuit contains(v: Vector<7, Uint<8>>, n: Uint<8>): Boolean {{
    return fold((acc: Boolean, x: Uint<8>): Boolean => acc || x == n, false, v);
  }}

  circuit valueMod(pair: Vector<2, Uint<8>>, m: Uint<16>): [Uint<16>, Uint<16>] {{
    const v = (pair[0] * 256 + pair[1]) as Uint<16>;
    const qr = disclose(divMod16(v, m));
    assert(qr[1] < m, "bad remainder");
    assert(qr[0] * m + qr[1] == v, "bad quotient");
    return [v, qr[1]];
  }}

  circuit pickMain(s: Pick, pair: Vector<2, Uint<8>>): Pick {{
    const vr = valueMod(pair, 35);
    const n = (vr[1] + 1) as Uint<8>;
    const take = vr[0] < 65520 && s.count < 7 && !contains(s.nums, n);
    return Pick {{
      nums: map((x: Uint<8>, j: Uint<8>): Uint<8> => (take && j == s.count) ? n : x, s.nums, {IDX7}),
      count: take ? (s.count + 1) as Uint<8> : s.count
    }};
  }}

  circuit pickMoonball(s: PickOne, pair: Vector<2, Uint<8>>): PickOne {{
    const vr = valueMod(pair, 20);
    const take = !s.found && vr[0] < 65520;
    return PickOne {{
      n: take ? (vr[1] + 1) as Uint<8> : s.n,
      found: s.found || take
    }};
  }}

  circuit sorted(v: Vector<7, Uint<8>>): Vector<7, Uint<8>> {{
    const s = disclose(sortSeven(v));
    assert(s[0] < s[1] && s[1] < s[2] && s[2] < s[3] && s[3] < s[4] && s[4] < s[5] && s[5] < s[6], "not sorted");
    assert(fold((acc: Boolean, x: Uint<8>): Boolean => acc && contains(v, x), true, s), "not the same numbers");
    return s;
  }}

  // The numbers for a draw seed (the site's `midnight_lotto_derive_numbers`
  // and `midnight_lotto_derive_bonus` for Starfall).
  export circuit numbersOf(drawSeed: Bytes<32>): Numbers {{
    const seedHex = toHex(drawSeed);
{main_digests()}
{main_folds()}
    assert(s{MAIN_DIGESTS}.count == 7, "not enough distinct numbers");
    const mb = fold(pickMoonball, PickOne {{ n: 0, found: false }}, pairsOf(sha69([...seedHex, 58, 109, 98, 58, 48])));
    assert(mb.found, "no Moonball");
    return Numbers {{ main: sorted(s{MAIN_DIGESTS}.nums), moonball: mb.n }};
  }}
}}
"""

OUT.write_text(SRC)
print(f"wrote {OUT}")
