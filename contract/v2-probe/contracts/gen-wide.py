#!/usr/bin/env python3
"""Write wide-N.compact: a contract with N circuits, each like Starfall's
changeOrganiser (a witness, a SHA-256 commitment, ledger writes), whose verifier
key is the largest kind Starfall v2 has (2,121 bytes on Compact 0.36). Deploying
these for growing N finds how many circuits one ledger 9 deploy transaction can
carry. Throwaway contracts: nothing calls them."""
import sys, pathlib
out = pathlib.Path(__file__).resolve().parent / "wide"
for n in [int(x) for x in sys.argv[1:]]:
    circuits = "\n".join(f"""export circuit c{i:02d}(x: Bytes<32>): [] {{
  assert(disclose(persistentHash<[Bytes<32>, Bytes<32>]>([pad(32, "probe:{i}"), secret()]) != x), "no");
  last = disclose(x);
  calls.increment(1);
}}
""" for i in range(n))
    (out / f"wide-{n}.compact").write_text(f"""// GENERATED by gen-wide.py: {n} circuits, for the ledger 9 deploy-size probe.
pragma language_version >= 0.28;
import CompactStandardLibrary;

export ledger last: Bytes<32>;
export ledger calls: Counter;
witness secret(): Bytes<32>;

{circuits}""")
    print(f"wrote wide-{n}.compact")
